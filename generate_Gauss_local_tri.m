function [Gauss_weights,Gauss_nodes]=generate_Gauss_local_tri(vertices,Gpn)
% 三角形单元局部高斯求积（标准 Dunavant 求积，参考三角 xi>=0,eta>=0,xi+eta<=1）
% vertices: 2×3 顶点矩阵，每列为一个顶点 [x;y]（与 P(:,T(:,n)) 一致）
% Gpn：求积阶数选择（1~5），对应可精确积分的多项式次数为 1~5
% Gauss_nodes: Ng×2 物理坐标高斯点，每行一个点
% Gauss_weights: Ng×1 权重（已乘雅可比行列式）
%
% 说明：先在重心坐标 (l1,l2,l3) 下查标准 Dunavant 表，再转直角坐标
%       xi=l2, eta=l3（参考顶点1=(0,0)对应 l1=1）；参考三角面积为 1/2，
%       故参考权重 = 归一化权重 / 2，最后乘物理雅可比行列式。

% ========== 参考三角上高斯点（标准 Dunavant 查表，直角坐标 xi,eta）==========
switch Gpn
    case 1
        % 1 点，1 阶
        xi_ref=[1/3];
        eta_ref=[1/3];
        w_ref=[1/2];

    case 2
        % 3 点，2 阶
        xi_ref=[1/6, 2/3, 1/6];
        eta_ref=[1/6, 1/6, 2/3];
        w_ref=[1/6, 1/6, 1/6];

    case 3
        % 4 点，3 阶
        xi_ref=[1/3, 0.6, 0.2, 0.2];
        eta_ref=[1/3, 0.2, 0.6, 0.2];
        w_ref=[-9/32, 25/96, 25/96, 25/96];

    case 4
        % 6 点，4 阶（iFEM 重心坐标转换，权重为参考权重）
        c1=0.108103018168070;   % 重心第一坐标（小值）
        c2=0.445948490915965;   % 重心另两个坐标
        d1=0.816847572980459;   % 靠近顶点的大坐标
        d2=0.091576213509771;   % 小坐标
        % 第一组：(c2,c2),(c1,c2),(c2,c1)，第二组：(d2,d2),(d1,d2),(d2,d1)
        xi_ref =[c2, c1, c2, d2, d1, d2];
        eta_ref=[c2, c2, c1, d2, d2, d1];
        w_ref=[0.111690794839005, 0.111690794839005, 0.111690794839005, ...
               0.054975871827661, 0.054975871827661, 0.054975871827661];

    case 5
        % 7 点，5 阶（iFEM 重心坐标转换，权重为参考权重）
        a1=0.059715871789770;   % 第一组小坐标
        b1=0.470142064105115;   % 第一组大坐标
        a2=0.797426985353087;   % 第二组大坐标
        b2=0.101286507323456;   % 第二组小坐标
        % 重心点；第一组：(b1,b1),(a1,b1),(b1,a1)；第二组：(b2,b2),(a2,b2),(b2,a2)
        xi_ref =[1/3, b1, a1, b1, b2, a2, b2];
        eta_ref=[1/3, b1, b1, a1, b2, b2, a2];
        w_ref=[0.112500000000000, ...
               0.066197076394253, 0.066197076394253, 0.066197076394253, ...
               0.062969590275838, 0.062969590275838, 0.062969590275838];

    otherwise
        error('暂时只支持 Gpn=1~5');
end
Ng=length(xi_ref);

% ========== 仿射映射：参考三角 -> 物理三角 ==========
x1=vertices(1,1); y1=vertices(2,1);
x2=vertices(1,2); y2=vertices(2,2);
x3=vertices(1,3); y3=vertices(2,3);
J=(x2-x1)*(y3-y1)-(x3-x1)*(y2-y1);
detJ=abs(J);

Gauss_nodes=zeros(Ng,2);
Gauss_weights=zeros(Ng,1);
for i=1:Ng
    xi=xi_ref(i);
    eta=eta_ref(i);
    x=x1+(x2-x1)*xi+(x3-x1)*eta;
    y=y1+(y2-y1)*xi+(y3-y1)*eta;
    Gauss_nodes(i,:)=[x,y];
    Gauss_weights(i)=w_ref(i)*detJ;
end
end