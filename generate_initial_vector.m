function u0 = generate_initial_vector(Pb)
% 【完善】生成初始时刻 t=0 时有限元节点上的初始值向量
% 题目给定初始条件：u(x,y,0) = e^(x+y)，在整个区域 Ω=[0,2]×[0,1] 上成立
%
% 输入：
%   Pb : 2×N 有限元节点坐标矩阵，每一列 [x;y] 为一个节点
% 输出：
%   u0 : N×1 初始值向量，u0(i) 为第 i 个节点上的初始温度值
%
% 说明：
%   对于本题，t=0 时刻四条边界上的初始值 e^(x+y) 与边界条件在 t=0 时
%   的取值（e^y、e^(2+y)、e^x、e^(x+1)）完全一致，因此无需对边界节点
%   做特殊处理，直接对全部节点统一赋值即可。

N = size(Pb, 2);
u0 = zeros(N, 1);

for i = 1:N
    x = Pb(1, i);
    y = Pb(2, i);
    % 【新增】初始条件 u(x,y,0) = e^(x+y)
    u0(i) = exp(x + y);
end

end
