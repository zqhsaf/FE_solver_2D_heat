% run_error_test.m
% Case 1: 一次三角元 (201) + 后退欧拉 (θ=1)，Δt = 4h²，t=1
% 遍历 h = 1/4, 1/8, 1/16, 1/32, 1/64，输出三类误差表格
%
% 参考表格：
%   h      ||u-uh||_∞    ||u-uh||_0    |u-uh|_1
%   1/4    3.7039e-1    1.9449e-1     2.5875e0
%   1/8    9.8704e-2    5.0853e-2     1.2865e0
%   1/16   2.5483e-2    1.2871e-2     6.4214e-1
%   1/32   6.4745e-3    3.2279e-3     3.2092e-1
%   1/64   1.6318e-3    8.0763e-4     1.6044e-1

clear; clc;

%% 问题参数
left   = 0;  right  = 2;      % x 方向
bottom = 0;  top    = 1;     % y 方向
start  = 0;  ending = 1;     % 时间区间
theta  = 1/2;                  % 后退欧拉
basis_type = 201;            % 一次三角元

%% 网格序列 h = 1/4, 1/8, 1/16
h_list = [1/4, 1/8, 1/16];
n_h = length(h_list);

% 预分配结果数组
Linf = zeros(n_h, 1);
L2   = zeros(n_h, 1);
H1   = zeros(n_h, 1);

fprintf('============================================================\n');
fprintf(' Case 1: 一次有限元 + 后退欧拉 (θ=1), Δt=4h², t=1\n');
fprintf('============================================================\n');
fprintf(' %-8s %-14s %-14s %-14s\n', 'h', '||u-uh||_∞', '||u-uh||_0', '|u-uh|_1');
fprintf('------------------------------------------------------------\n');

for i = 1 : n_h
    h = h_list(i);

    % x 方向长度为 2，y 方向长度为 1，统一步长 h
    N1 = round((right - left)  / h);     % = 2/h
    N2 = round((top  - bottom) / h);     % = 1/h

    % 时间步长 Δt = 4h²
    dt = h;

    % 调用主求解器，返回解和三类误差
    [~, Linf(i), L2(i), H1(i)] = FE_solver_2D_heat( ...
        start, ending, dt, theta, ...
        left, right, bottom, top, ...
        basis_type, basis_type, N1, N2);

    % 打印当前行
    fprintf(' 1/%-6d %-14.4e %-14.4e %-14.4e\n', ...
        round(1/h), Linf(i), L2(i), H1(i));
end

fprintf('============================================================\n');

%% 计算收敛阶（相邻两行之比的 log2）
fprintf('\n收敛阶（每细分一倍网格，误差衰减的倍数 / 2^p）：\n');
fprintf(' %-8s %-14s %-14s %-14s\n', 'h', 'rate_∞', 'rate_0', 'rate_1');
fprintf('------------------------------------------------------------\n');
for i = 2 : n_h
    p_inf = log2(Linf(i-1) / Linf(i));
    p_0   = log2(L2(i-1)   / L2(i));
    p_1   = log2(H1(i-1)   / H1(i));
    fprintf(' 1/%-6d %-14.2f %-14.2f %-14.2f\n', ...
        round(1/h_list(i)), p_inf, p_0, p_1);
end
fprintf('============================================================\n');
fprintf('预期：一次元 L∞/L2 约 O(h²)，H1 半范数约 O(h)\n');
